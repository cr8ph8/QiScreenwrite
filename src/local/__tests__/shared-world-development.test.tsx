import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { DevelopmentPanel } from '../components/DevelopmentPanel';
import { localApi, LocalApiError } from '../api';
import { createDevelopment, developmentSave, developmentId, type DevelopmentData } from '../development';
import { buildDraftData } from '../model';
import { newWorldElement, newWorldLink } from '../world';
import { initialize, WorkspaceStore } from '../../../local/server/storage.mjs';
import { validateRecord } from '../../../local/server/contracts.mjs';
import { DevelopmentRecoveryStore } from '../../../local/server/recovery.mjs';

const firstDraft = 'screenplay-draft:aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa';
const secondDraft = 'screenplay-draft:bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb';
let directory: string;
let store: InstanceType<typeof WorkspaceStore>;
let projectId: string;
const click = (name: string | RegExp) => fireEvent.click(screen.getByRole('button', { name }));
const tab = (name: string) => fireEvent.mouseDown(screen.getByRole('tab', { name }), { button: 0, ctrlKey: false });
const write = (name: string, value: string) => fireEvent.change(screen.getByRole('textbox', { name }), { target: { value } });
const flush = () => (window as unknown as { __flushDevelopmentRecovery: () => Promise<void> }).__flushDevelopmentRecovery();
async function setup(draftId: string, onOpenDraft?: (id: string) => void) {
  const view = render(<DevelopmentPanel projectId={projectId} draftId={draftId} view="world" initialRecord={store.current(developmentId(draftId))} onSaved={() => {}} onOpenDraft={onOpenDraft} />);
  await act(async () => {});
  return view;
}
beforeEach(() => {
  localStorage.clear();
  directory = fs.mkdtempSync(path.join(os.tmpdir(), 'shared-world-development-'));
  initialize(directory); store = new WorkspaceStore(directory, validateRecord); projectId = store.project().id;
  for (const id of [firstDraft, secondDraft]) store.save(id, { kind: 'screenplay-draft', expectedVersion: null, requestId: crypto.randomUUID(), data: buildDraftData(projectId, { title: 'Disposable draft', body: 'INT. LAB - DAY\n\nMIRA\nHello.' }) });
  const element = { ...newWorldElement('location'), name: 'Original place', description: 'Owner description.' };
  const data: DevelopmentData = { ...createDevelopment(projectId, firstDraft), concept: 'Owner concept.', worldNotes: 'Owner overview.', schemaVersion: 2, world: { schemaVersion: 1, elements: [element], links: [{ ...newWorldLink(element.id, 'scene', 'number:1', 'INT. LAB - DAY'), notes: 'Specific scene note.' }] } };
  const { id, ...input } = developmentSave(data, null); store.save(id, input);
  vi.spyOn(localApi, 'bootstrap').mockImplementation(async () => ({ project: store.project(), records: store.list(), connectors: { qimovi: { configured: false, origin: null, connected: false, project: null } } }));
  vi.spyOn(localApi, 'history').mockImplementation(async id => store.history(id));
  vi.spyOn(localApi, 'save').mockImplementation(async ({ id, ...input }) => store.save(id, input));
  vi.spyOn(localApi.developmentRecovery, 'get').mockImplementation(async draftId => new DevelopmentRecoveryStore(store).get(draftId));
  vi.spyOn(localApi.developmentRecovery, 'put').mockImplementation(async copy => new DevelopmentRecoveryStore(store).put(copy.draftId, copy));
  vi.spyOn(localApi.developmentRecovery, 'remove').mockImplementation(async (draftId, savedAt) => new DevelopmentRecoveryStore(store).delete(draftId, savedAt));
});
afterEach(async () => { cleanup(); await act(async () => {}); vi.restoreAllMocks(); store.close(); fs.rmSync(directory, { recursive: true, force: true }); });

describe('shared library inside durable draft development', () => {
  it('keeps WorldBuilder mounted and unsaved notes intact through library and global view changes', async () => {
    const view = await setup(firstDraft);
    click(/Location Original place/); const originalInput = screen.getByRole('textbox', { name: 'Element name' });
    write('Element name', 'Unsaved renamed place'); write('Description', 'Unsaved owner text.');
    tab('Shared library'); await waitFor(() => expect(screen.getByRole('button', { name: 'New shared world' })).toBeEnabled());
    write('Shared world name', 'Stories'); tab('Draft world');
    expect(screen.getByRole('textbox', { name: 'Element name' })).toBe(originalInput);
    expect(originalInput).toHaveValue('Unsaved renamed place');
    view.rerender(<DevelopmentPanel projectId={projectId} draftId={firstDraft} view="develop" onSaved={() => {}} />);
    view.rerender(<DevelopmentPanel projectId={projectId} draftId={firstDraft} view="world" onSaved={() => {}} />);
    expect(screen.getByRole('textbox', { name: 'Description' })).toHaveValue('Unsaved owner text.');
    tab('Shared library'); expect(screen.getByRole('textbox', { name: 'Shared world name' })).toHaveValue('Stories');
    await act(async () => flush());
    const recovery = new DevelopmentRecoveryStore(store).get(firstDraft);
    expect(recovery.data.world.elements[0]).toMatchObject({ name: 'Unsaved renamed place', description: 'Unsaved owner text.' });
    expect(store.current(developmentId(firstDraft)).data.world.elements[0].name).toBe('Original place');
  });
  it('publishes from one draft, imports to another, then restores the unsaved import after browser storage is lost', async () => {
    const first = await setup(firstDraft);
    const original = store.current(developmentId(firstDraft));
    tab('Shared library'); await waitFor(() => expect(screen.getByRole('button', { name: 'New shared world' })).toBeEnabled());
    write('Shared world name', 'Shared setting'); click('Preview publication as new world'); click('Publish snapshot');
    await waitFor(() => expect(screen.getByText(/Published “Shared setting” v1/)).toBeInTheDocument());
    expect(store.current(developmentId(firstDraft))).toEqual(original);
    const shared = store.list().find(record => record.kind === 'shared-world');
    expect(shared.data.world.links).toEqual([]);
    await act(async () => flush()); first.unmount();
    const second = await setup(secondDraft);
    tab('Shared library'); await waitFor(() => expect(screen.getByRole('button', { name: /Shared setting v1/ })).toBeEnabled());
    click(/Shared setting v1/); click('Preview adding to draft'); click('Add snapshot to draft');
    await act(async () => flush());
    const recovery = new DevelopmentRecoveryStore(store).get(secondDraft);
    expect(recovery.data).toMatchObject({ schemaVersion: 2, draftId: secondDraft, world: { elements: [{ name: 'Original place' }], links: [] } });
    expect(recovery.data.world.elements[0].id).not.toBe(shared.data.world.elements[0].id);
    expect(recovery.data.worldNotes).toContain('From shared world: Shared setting (v1)\n\nOwner overview.');
    expect(store.current(developmentId(secondDraft))).toBeNull();
    second.unmount(); localStorage.clear(); store.close(); store = new WorkspaceStore(directory, validateRecord);
    await setup(secondDraft);
    expect(screen.getByRole('region', { name: 'Development recovery' })).toBeInTheDocument(); click('Restore recovery'); click('Save development');
    await waitFor(() => expect(screen.getByRole('button', { name: 'Save development' })).toBeDisabled());
    expect(store.current(developmentId(secondDraft)).data).toEqual(recovery.data);
    expect(store.current(shared.id)).toEqual(shared); expect(store.current(developmentId(firstDraft))).toEqual(original);
  });
  it('blocks draft switch and native close while a library publication is unconfirmed, including while hidden', async () => {
    await setup(firstDraft); tab('Shared library');
    await waitFor(() => expect(screen.getByRole('button', { name: 'New shared world' })).toBeEnabled());
    vi.mocked(localApi.save).mockRejectedValueOnce(new LocalApiError('Lost response', 0, 'SERVICE_UNREACHABLE'));
    write('Shared world name', 'Shared setting'); click('Preview publication as new world'); click('Publish snapshot');
    await waitFor(() => expect(screen.getByRole('button', { name: 'Retry publication' })).toBeInTheDocument());
    tab('Draft world'); await expect(flush()).rejects.toThrow('retry the shared world save');
    tab('Shared library'); click('Retry publication');
    await waitFor(() => expect(screen.getByText(/Published “Shared setting” v1/)).toBeInTheDocument());
    await act(async () => flush());
  });
  it('tracks publication and imports a linked world, then reviews library changes without overwriting draft edits', async () => {
    const first = await setup(firstDraft);
    tab('Shared library'); await waitFor(() => expect(screen.getByRole('button', { name: 'New shared world' })).toBeEnabled());
    write('Shared world name', 'Connected setting'); click('Preview publication as new world'); click('Publish snapshot');
    await waitFor(() => expect(screen.getByText(/Published “Connected setting” v1/)).toBeInTheDocument());
    click('Track this publication'); click('Track published revision');
    await waitFor(() => expect(screen.getByText('This draft follows v1')).toBeInTheDocument());
    click('Save development'); await waitFor(() => expect(screen.getByRole('button', { name: 'Save development' })).toBeDisabled());
    const shared = store.list().find(record => record.kind === 'shared-world');
    const original = store.current(developmentId(firstDraft));
    expect(original.data.schemaVersion).toBe(3);
    expect(original.data.worldSources[0].elements[0]).toEqual({ sourceId: shared.data.world.elements[0].id, localId: shared.data.world.elements[0].id });
    expect(original.data.world.links[0].notes).toBe('Specific scene note.');
    first.unmount();
    const openDraft = vi.fn();
    await setup(secondDraft, openDraft); tab('Shared library');
    await waitFor(() => expect(screen.getByRole('button', { name: /Connected setting v1/ })).toBeEnabled());
    click(/Connected setting v1/); click('Preview linked import'); click('Link world to draft');
    await waitFor(() => expect(screen.getByText('This draft follows v1')).toBeInTheDocument());
    tab('Draft world'); click(/Location Original place/); write('Description', 'Specific to this screenplay.');
    click('Save development'); await waitFor(() => expect(screen.getByRole('button', { name: 'Save development' })).toBeDisabled());
    const before = store.current(developmentId(secondDraft));
    const nextLibrary = structuredClone(shared.data);
    nextLibrary.world.elements[0].description = 'New library description.';
    nextLibrary.world.elements[0].sensoryDetails = 'A foghorn sounds.';
    const revised = store.save(shared.id, { kind: 'shared-world', expectedVersion: 1, requestId: crypto.randomUUID(), data: nextLibrary });
    tab('Shared library'); click('Refresh library');
    await waitFor(() => expect(screen.getByRole('button', { name: 'Review library updates' })).toBeEnabled());
    click('Review library updates');
    await waitFor(() => expect(screen.getByRole('combobox', { name: 'Keep version for Original place Description' })).toBeInTheDocument());
    expect(screen.getByRole('button', { name: 'Apply reviewed update' })).toBeDisabled();
    fireEvent.change(screen.getByRole('combobox', { name: 'Keep version for Original place Description' }), { target: { value: 'draft' } });
    click('Apply reviewed update');
    await waitFor(() => expect(screen.getByText('This draft follows v2')).toBeInTheDocument());
    click('Save development'); await waitFor(() => expect(screen.getByRole('button', { name: 'Save development' })).toBeDisabled());
    const after = store.current(developmentId(secondDraft));
    expect(after.data.world.elements).toHaveLength(1);
    expect(after.data.world.elements[0]).toMatchObject({ id: before.data.world.elements[0].id, description: 'Specific to this screenplay.', sensoryDetails: 'A foghorn sounds.' });
    expect(after.data.worldSources[0]).toMatchObject({ worldId: shared.id, version: 2, sha256: revised.sha256 });
    expect(after.data.worldNotes).toBe(before.data.worldNotes);
    expect(store.current(developmentId(firstDraft))).toEqual(original);
    click('Refresh library');
    await waitFor(() => expect(screen.getByText('Used in 2 saved drafts')).toBeInTheDocument());
    fireEvent.click(screen.getByText('Used in 2 saved drafts'));
    click('Disposable draft'); expect(openDraft).toHaveBeenCalledWith(firstDraft);
  }, 20000);

  it('refuses a linked import if the library or draft changes while it is being confirmed', async () => {
    const first = await setup(firstDraft); tab('Shared library');
    await waitFor(() => expect(screen.getByRole('button', { name: 'New shared world' })).toBeEnabled());
    write('Shared world name', 'Moving setting'); click('Preview publication as new world'); click('Publish snapshot');
    await waitFor(() => expect(screen.getByText(/Published “Moving setting” v1/)).toBeInTheDocument());
    first.unmount(); await setup(secondDraft); tab('Shared library');
    await waitFor(() => expect(screen.getByRole('button', { name: /Moving setting v1/ })).toBeEnabled());
    click(/Moving setting v1/); click('Preview linked import');
    const shared = store.list().find(record => record.kind === 'shared-world');
    store.save(shared.id, { kind: 'shared-world', expectedVersion: 1, requestId: crypto.randomUUID(), data: { ...shared.data, description: 'Changed after preview.' } });
    click('Link world to draft');
    await waitFor(() => expect(screen.getByRole('alert')).toHaveTextContent('library changed after this preview'));
    expect(screen.queryByText('This draft follows v1')).not.toBeInTheDocument();
    expect(store.current(developmentId(secondDraft))).toBeNull();
    expect(new DevelopmentRecoveryStore(store).get(secondDraft)).toBeNull();
  }, 15000);

});
