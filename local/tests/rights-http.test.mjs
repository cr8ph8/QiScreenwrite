import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { initialize, loadConfig } from '../server/storage.mjs';
import { startServer } from '../server/http.mjs';
import { RIGHTS_ID, defaultParticipation, recordRef, emptyPublicFields } from '../contracts/writer-rights.mjs';

test('rights routes enforce owner/origin, byte validation, stale metadata export and no chain execution', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'rights-http-'));
  initialize(root); const server = await startServer({ directory: root });
  t.after(async () => { await server.close(); fs.rmSync(root, { recursive: true, force: true }); });
  const origin = server.origin;
  const login = await fetch(origin + '/api/session', { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ token: loadConfig(root).ownerToken }) });
  const headers = { Origin: origin, Cookie: login.headers.get('set-cookie').split(';')[0], 'Content-Type': 'application/json' };
  const req = (route, value, extra = {}) => fetch(origin + route, { headers, ...(value === undefined ? {} : { method: 'POST', body: JSON.stringify(value) }), ...extra });
  const { project } = await (await req('/api/bootstrap')).json();
  const upload = { name: 'private.txt', mediaType: 'text/plain', base64: Buffer.from('Private evidence').toString('base64') };
  assert.equal((await req('/api/rights/evidence', upload, { headers: { ...headers, Cookie: '' } })).status, 401);
  assert.equal((await req('/api/rights/evidence', upload, { headers: { ...headers, Origin: 'https://foreign.invalid' } })).status, 403);
  assert.equal((await req('/api/rights/evidence', { ...upload, path: '/etc/passwd' })).status, 422);
  const attached = await req('/api/rights/evidence', upload); assert.equal(attached.status, 200); const evidence = await attached.json();
  const save = (id, data, version = null) => req('/api/records/' + encodeURIComponent(id), { kind: id.split(':')[0], data, expectedVersion: version, requestId: crypto.randomUUID() }, { method: 'PUT' });
  const ledgerReply = await save(RIGHTS_ID, defaultParticipation(project)); assert.equal(ledgerReply.status, 200); const ledger = await ledgerReply.json();
  const recovery = { schemaVersion: 1, projectId: project.id, baseVersion: ledger.version, baseSha256: ledger.sha256, data: ledger.data, pendingSave: null, savedAt: '2026-09-27T18:00:00.000Z' };
  assert.equal((await req('/api/rights/recovery', recovery, { method: 'PUT' })).status, 200);
  assert.deepEqual(await (await req('/api/rights/recovery')).json(), recovery);
  assert.equal((await req('/api/rights/recovery?savedAt=wrong', undefined, { method: 'DELETE' })).status, 409);
  assert.equal((await req('/api/rights/recovery?savedAt=' + encodeURIComponent(recovery.savedAt), undefined, { method: 'DELETE' })).status, 200);
  assert.equal((await req('/api/rights/worksheet', recordRef(ledger))).status, 200);
  const data = { schemaVersion: 1, projectId: project.id, status: 'DRAFT', subjectRef: recordRef(evidence), participationRef: recordRef(ledger), standard: 'ERC721', editionCap: 1, royaltyRequestBps: null, publicFields: { ...emptyPublicFields(), name: 'Public draft' }, nonce: 'a'.repeat(64) };
  const tokenReply = await save('token-preparation:one', data); assert.equal(tokenReply.status, 200); const token = await tokenReply.json();
  const preview = await (await req('/api/rights/token-preview', recordRef(token))).json();
  assert.equal((await req('/api/rights/token-export', { recordRef: recordRef(token), metadataSha256: preview.metadataSha256 })).status, 200);
  const updated = { ...ledger.data, parties: [{ id: 'person', name: 'Private name', kind: 'PERSON' }] };
  assert.equal((await save(RIGHTS_ID, updated, ledger.version)).status, 200);
  assert.equal((await req('/api/rights/token-export', { recordRef: recordRef(token), metadataSha256: preview.metadataSha256 })).status, 409);
  assert.equal((await req('/api/rights/mint', {})).status, 404);
  assert.equal((await req('/api/rights/sign', {})).status, 404);
});
