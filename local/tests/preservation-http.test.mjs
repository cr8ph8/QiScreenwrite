import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { initialize, loadConfig } from '../server/storage.mjs';
import { startServer } from '../server/http.mjs';

test('preservation endpoints require owner scope, reject stale reviews and verify without writing records', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'writer-preservation-http-'));
  initialize(directory, { title: 'Disposable preservation HTTP test' });
  const server = await startServer({ directory });
  t.after(async () => { await server.close(); fs.rmSync(directory, { recursive: true, force: true }); });
  const origin = server.origin;
  assert.equal((await fetch(origin + '/api/preservation')).status, 401);
  const session = await fetch(origin + '/api/session', { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ token: loadConfig(directory).ownerToken }) });
  const cookie = session.headers.get('set-cookie').split(';')[0];
  const headers = { Origin: origin, Cookie: cookie, 'Content-Type': 'application/json' };
  const request = (route, value, overrides = {}) => fetch(origin + route, { headers, ...(value === undefined ? {} : { method: 'POST', body: JSON.stringify(value) }), ...overrides });
  const boot = await (await request('/api/bootstrap')).json();
  const data = { schemaVersion: 2, projectId: boot.project.id, sourceHash: null, title: 'The Harbor', format: 'FOUNTAIN', body: 'EXT. HARBOR - DAWN\n\nWaves break.', status: 'DRAFT' };
  const save = (version, body) => request('/api/records/screenplay-draft:harbor', { kind: 'screenplay-draft', data: { ...data, body }, expectedVersion: version, requestId: `save-${version}` }, { method: 'PUT' });
  assert.equal((await save(null, data.body)).status, 200);
  const preview = await (await request('/api/preservation')).json();
  assert.equal(preview.inventory.length, 1);
  assert.equal((await request('/api/preservation/export', { sourceSha256: preview.sourceSha256 }, { headers: { ...headers, Origin: 'https://foreign.example' } })).status, 403);
  assert.equal((await request('/api/preservation/export', { sourceSha256: preview.sourceSha256, unexpected: true })).status, 422);
  const exported = await request('/api/preservation/export', { sourceSha256: preview.sourceSha256 }); assert.equal(exported.status, 200);
  const packet = await exported.json();
  const before = await (await request('/api/bootstrap')).json();
  const verification = await request('/api/preservation/verify', packet); assert.equal(verification.status, 200);
  assert.equal((await verification.json()).valid, true);
  assert.deepEqual(await (await request('/api/bootstrap')).json(), before);
  const corrupt = structuredClone(packet); corrupt.backup.records[0].data.body = 'Changed bytes';
  assert.equal((await request('/api/preservation/verify', corrupt)).status, 422);
  assert.equal((await save(1, 'New saved version.')).status, 200);
  assert.equal((await request('/api/preservation/export', { sourceSha256: preview.sourceSha256 })).status, 409);
  const fresh = await (await request('/api/preservation')).json(); assert.notEqual(fresh.sourceSha256, preview.sourceSha256); assert.equal(fresh.revisionCount, 2);
});
